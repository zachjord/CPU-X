import argparse
import datetime
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def validate(data):
    if set(data) != {'schema_version', 'sources', 'records'} or data['schema_version'] != 1:
        raise ValueError('unsupported schema')
    if not isinstance(data['sources'], dict) or not data['sources']:
        raise ValueError('sources must be a nonempty object')
    for source in data['sources'].values():
        if source.get('type') not in ('inherited', 'manufacturer'):
            raise ValueError('invalid source type')
        if not isinstance(source.get('url'), str) or not source['url'].startswith('https://'):
            raise ValueError('source must have an HTTPS URL')
        if source['type'] == 'manufacturer':
            datetime.date.fromisoformat(source['retrieved'])
    if not isinstance(data['records'], list) or not data['records']:
        raise ValueError('records must be a nonempty array')
    seen = set()
    required = {'vendor', 'codename', 'model', 'socket', 'match', 'source', 'status'}
    for r in data['records']:
        if not required <= r.keys() or r.keys() - required - {'display_codename'}:
            raise ValueError('missing or unknown record fields')
        for key in ('codename', 'model', 'socket', 'display_codename'):
            value = r.get(key)
            if value is not None and (not isinstance(value, str) or not value.strip() or any(ord(c) < 32 for c in value)):
                raise ValueError('invalid text: ' + key)
        if r['vendor'] not in ('amd', 'intel') or not r['socket']:
            raise ValueError('invalid vendor or socket')
        if not (r['codename'] or r['model']) or r['match'] not in ('exact', 'legacy'):
            raise ValueError('invalid match')
        if r['source'] not in data['sources'] or r['status'] != data['sources'][r['source']]['type']:
            raise ValueError('invalid provenance')
        if r['match'] == 'exact' and (not r['model'] or r['codename'] is not None or r['status'] != 'manufacturer'):
            raise ValueError('exact models require manufacturer provenance and no codename predicate')
        if 'display_codename' in r and r['match'] != 'exact':
            raise ValueError('only exact model rules may override codenames')
        key = (r['vendor'], r['match'], ' '.join((r['codename'] or '').lower().split()), ' '.join((r['model'] or '').lower().split()))
        if key in seen:
            raise ValueError('duplicate or conflicting match: ' + repr(key))
        seen.add(key)
    return data


def generate(data):
    validate(data)
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Generated by scripts/generate_package_database.py; do not edit.',
             '// Inherited mappings: Copyright 2014-2025 The Tumultuous Unicorn Of Darkness.',
             '#ifndef CPUX_PACKAGE_DATABASE_H', '#define CPUX_PACKAGE_DATABASE_H',
             'struct Package_DB {', '\tconst char *codename;', '\tconst char *model;',
             '\tconst char *socket;', '\tbool exact;', '\tconst char *display_codename;',
             '\tconst char *source;', '};']
    def literal(value):
        return 'nullptr' if value is None else json.dumps(value, ensure_ascii=True)
    for vendor in ('intel', 'amd'):
        lines.append('inline constexpr Package_DB package_' + vendor + '[] = {')
        for r in data['records']:
            if r['vendor'] != vendor:
                continue
            fields = [literal(r[k]) for k in ('codename', 'model', 'socket')]
            fields += ['true' if r['match'] == 'exact' else 'false', literal(r.get('display_codename')), literal(r['source'])]
            lines.append('\t{ ' + ', '.join(fields) + ' },')
        lines += ['\t{ nullptr, nullptr, nullptr, false, nullptr, nullptr }', '};']
    return '\n'.join(lines + ['#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT / 'data/processors/packages.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'src/core/databases.h')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        result = generate(json.loads(args.input.read_text()))
        if args.check:
            if not args.output.exists() or args.output.read_text() != result:
                parser.exit(1, 'generated package database is stale; run scripts/generate_package_database.py\n')
        else:
            args.output.write_text(result)
    except (ValueError, KeyError, TypeError, OSError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
